/** Returns the catalog icon for this achievement, including for older DB records. */
export function getAchievementIconSlug(
  iconSlug: string,
  achievementKey?: string
): string {
  return (achievementKey ? ACHIEVEMENT_ICON_BY_KEY[achievementKey] : undefined)
    ?? ACHIEVEMENT_ICON_ALIASES[iconSlug]
    ?? iconSlug;
}
